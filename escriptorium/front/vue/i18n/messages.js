function mergeLocale(base, extra) {
    const out = { ...base };
    Object.keys(extra || {}).forEach((key) => {
        if (
            base[key]
            && extra[key]
            && typeof base[key] === "object"
            && typeof extra[key] === "object"
            && !Array.isArray(base[key])
        ) {
            out[key] = mergeLocale(base[key], extra[key]);
        } else {
            out[key] = extra[key];
        }
    });
    return out;
}

